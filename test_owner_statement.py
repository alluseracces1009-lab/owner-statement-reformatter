"""Tests: python3 -m pytest -q test_owner_statement.py"""
from decimal import Decimal
from pathlib import Path

import pandas as pd
import pytest

import owner_statement as os_

HERE = Path(__file__).parent
EXPORT = HERE / "maple_ridge_oct2026_gl_export.csv"
WANT_SUMMARY = HERE / "tests" / "desired_output_owner_summary.csv"
WANT_SCHED_E = HERE / "tests" / "desired_output_schedule_e.csv"
PROFILE = HERE / "tests" / "whitfield_profile.json"


def amounts(series):
    return [os_.parse_money(v) if str(v).strip() not in ("", "nan") else None for v in series]


def test_matches_desired_amounts_to_the_penny(tmp_path):
    summary, sched_e, _ = os_.run(EXPORT, profile_path=PROFILE, outdir=tmp_path)
    want = pd.read_csv(WANT_SUMMARY, dtype=str, keep_default_na=False)
    assert list(summary["Section"]) == list(want["Section"])
    assert [v for v in summary["Amount"]] == amounts(want["Amount"])

    want_e = pd.read_csv(WANT_SCHED_E, dtype=str, keep_default_na=False)
    assert list(sched_e["Schedule E Line"]) == list(want_e["Schedule E Line"])
    assert list(sched_e["October 2026"]) == amounts(want_e["October 2026"])


def test_header_found_with_renamed_columns_and_extra_junk(tmp_path):
    text = EXPORT.read_text().replace("Cash In,Cash Out", "Cash In ,cash_out").replace(
        "GL Account", "Account Name").replace("Payee / Payer", "Payee")
    p = tmp_path / "variant.csv"
    p.write_text("Generated by AppFolio\n\n" + text)
    _, _, totals = os_.run(p, outdir=tmp_path)
    assert totals.expenses == Decimal("1629.49")


def test_unmapped_gl_is_an_error_not_silently_dropped(tmp_path):
    p = tmp_path / "new_gl.csv"
    p.write_text(EXPORT.read_text().replace("Pest Control,Quarterly", "6630 Snow Plowing,Quarterly"))
    with pytest.raises(KeyError, match="Snow Plowing"):
        os_.run(p, outdir=tmp_path)


def test_broken_balance_fails_validation(tmp_path):
    p = tmp_path / "bad.csv"
    p.write_text(EXPORT.read_text().replace(',,140.00,"2,657.68"', ',,140.10,"2,657.68"'))
    with pytest.raises(ValueError, match="Validation failed"):
        os_.run(p, outdir=tmp_path)


@pytest.mark.parametrize("raw,want", [
    ("1,450.00", "1450.00"), ("$1,450.00", "1450.00"), ("(48.17)", "-48.17"),
    ("48.17-", "-48.17"), ("", "0.00"), ("-", "0.00")])
def test_parse_money(raw, want):
    assert os_.parse_money(raw) == Decimal(want)


@pytest.mark.parametrize("raw,want", [
    ("4100 Rent Income", "rent income"), ("Rent Income", "rent income"),
    ("4105 - Late Fee Income", "late fee income"),
    ("4120 Other Income : Pet Rent", "other income:pet rent")])
def test_normalize_gl(raw, want):
    assert os_.normalize_gl(raw) == want
